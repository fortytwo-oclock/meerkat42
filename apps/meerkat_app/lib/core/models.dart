import 'dart:convert';

class HubConnectionConfig {
  const HubConnectionConfig({
    required this.hubBaseUrl,
    required this.operatorToken,
    this.enrollmentToken = '',
    this.clientGroup = 'default',
    this.lockedByMdm = false,
  });

  final String hubBaseUrl;
  final String operatorToken;
  final String enrollmentToken;
  final String clientGroup;
  final bool lockedByMdm;

  bool get isConfigured => hubBaseUrl.trim().isNotEmpty;

  /// Converts an HTTP(S) Hub URL into the agent WebSocket endpoint URL.
  String get agentStreamUrl {
    final trimmed = hubBaseUrl.trim().replaceAll(RegExp(r'/+$'), '');
    if (trimmed.startsWith('ws://') || trimmed.startsWith('wss://')) {
      return trimmed.endsWith('/api/v1/agent/stream')
          ? trimmed
          : '$trimmed/api/v1/agent/stream';
    }
    if (trimmed.startsWith('https://')) {
      return '${trimmed.replaceFirst('https://', 'wss://')}/api/v1/agent/stream';
    }
    if (trimmed.startsWith('http://')) {
      return '${trimmed.replaceFirst('http://', 'ws://')}/api/v1/agent/stream';
    }
    return 'wss://$trimmed/api/v1/agent/stream';
  }

  /// Normalizes a WebSocket or HTTP Hub URL into an HTTP(S) REST base URL.
  String get restBaseUrl {
    var trimmed = hubBaseUrl.trim().replaceAll(RegExp(r'/+$'), '');
    trimmed = trimmed.replaceFirst(RegExp(r'/api/v1/agent/stream$'), '');
    if (trimmed.startsWith('wss://')) {
      return trimmed.replaceFirst('wss://', 'https://');
    }
    if (trimmed.startsWith('ws://')) {
      return trimmed.replaceFirst('ws://', 'http://');
    }
    if (!trimmed.startsWith('http://') && !trimmed.startsWith('https://')) {
      return 'https://$trimmed';
    }
    return trimmed;
  }

  /// Parses a pairing URI generated by the Hub's "Add Device" onboarding modal:
  /// `meerkat42://enroll?hub=wss%3A%2F%2F...&token=cpa_...&group=default`
  static HubConnectionConfig? tryParseEnrollmentUri(String raw) {
    final uri = Uri.tryParse(raw.trim());
    if (uri == null || uri.scheme != 'meerkat42' || uri.host != 'enroll') {
      return null;
    }
    final hub = uri.queryParameters['hub']?.trim() ?? '';
    if (hub.isEmpty) return null;
    return HubConnectionConfig(
      hubBaseUrl: hub,
      operatorToken: uri.queryParameters['operator_token']?.trim() ?? '',
      enrollmentToken: uri.queryParameters['token']?.trim() ?? '',
      clientGroup: uri.queryParameters['group']?.trim().isNotEmpty == true
          ? uri.queryParameters['group']!.trim()
          : 'default',
    );
  }

  HubConnectionConfig copyWith({
    String? hubBaseUrl,
    String? operatorToken,
    String? enrollmentToken,
    String? clientGroup,
    bool? lockedByMdm,
  }) {
    return HubConnectionConfig(
      hubBaseUrl: hubBaseUrl ?? this.hubBaseUrl,
      operatorToken: operatorToken ?? this.operatorToken,
      enrollmentToken: enrollmentToken ?? this.enrollmentToken,
      clientGroup: clientGroup ?? this.clientGroup,
      lockedByMdm: lockedByMdm ?? this.lockedByMdm,
    );
  }
}

class DeviceLocation {
  const DeviceLocation({
    required this.lat,
    required this.lon,
    this.accuracyM,
    this.zone,
    this.source,
    this.updatedAt,
  });

  final double lat;
  final double lon;
  final double? accuracyM;
  final String? zone;
  final String? source;
  final String? updatedAt;

  factory DeviceLocation.fromJson(Map<String, dynamic> json) {
    return DeviceLocation(
      lat: (json['lat'] as num).toDouble(),
      lon: (json['lon'] as num).toDouble(),
      accuracyM: (json['accuracy_m'] as num?)?.toDouble(),
      zone: json['zone'] as String?,
      source: json['source'] as String?,
      updatedAt: json['updated_at'] as String?,
    );
  }

  Map<String, dynamic> toJson() => {
        'lat': lat,
        'lon': lon,
        if (accuracyM != null) 'accuracy_m': accuracyM,
        if (zone != null) 'zone': zone,
        if (source != null) 'source': source,
        if (updatedAt != null) 'updated_at': updatedAt,
      };
}

class NodeSummary {
  const NodeSummary({
    required this.nodeId,
    required this.hostname,
    required this.deviceClass,
    required this.clientGroup,
    required this.status,
    required this.cpuUsagePct,
    required this.ramUsagePct,
    required this.load1,
    this.platform,
    this.arch,
    this.lastSeen,
    this.batteryPct,
    this.containersRunning = 0,
    this.containersTotal = 0,
    this.lastLocation,
  });

  final String nodeId;
  final String hostname;
  final String deviceClass;
  final String? platform;
  final String? arch;
  final String clientGroup;
  final String status;
  final String? lastSeen;
  final double cpuUsagePct;
  final double ramUsagePct;
  final double load1;
  final double? batteryPct;
  final int containersRunning;
  final int containersTotal;
  final DeviceLocation? lastLocation;

  factory NodeSummary.fromJson(Map<String, dynamic> json) {
    final loc = json['last_location'];
    return NodeSummary(
      nodeId: json['node_id'] as String? ?? '',
      hostname: json['hostname'] as String? ?? 'unknown',
      deviceClass: json['device_class'] as String? ?? 'server',
      platform: json['platform'] as String?,
      arch: json['arch'] as String?,
      clientGroup: json['client_group'] as String? ?? 'default',
      status: json['status'] as String? ?? 'UNKNOWN',
      lastSeen: json['last_seen'] as String?,
      cpuUsagePct: (json['cpu_usage_pct'] as num?)?.toDouble() ?? 0,
      ramUsagePct: (json['ram_usage_pct'] as num?)?.toDouble() ?? 0,
      load1: (json['load_1'] as num?)?.toDouble() ?? 0,
      batteryPct: (json['battery_pct'] as num?)?.toDouble(),
      containersRunning: (json['containers_running'] as num?)?.toInt() ?? 0,
      containersTotal: (json['containers_total'] as num?)?.toInt() ?? 0,
      lastLocation: loc is Map<String, dynamic>
          ? DeviceLocation.fromJson(loc)
          : null,
    );
  }
}

