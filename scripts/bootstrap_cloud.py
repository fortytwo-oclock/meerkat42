#!/usr/bin/env python3
"""Create a secure environment file for the PostgreSQL/Redis topology."""

from __future__ import annotations

import argparse
import base64
import os
from pathlib import Path
import secrets

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ed25519


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "deploy" / "cloud.env"


def generate_keypair() -> tuple[str, str]:
    private = ed25519.Ed25519PrivateKey.generate()
    private_bytes = private.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public_bytes = private.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    return (
        base64.b64encode(private_bytes).decode("ascii"),
        base64.b64encode(public_bytes).decode("ascii"),
    )


def write_config(path: Path, *, domain: str, force: bool) -> None:
    if path.exists() and not force:
        raise SystemExit(f"Refusing to overwrite {path}. Use --force to replace it.")

    postgres_password = secrets.token_urlsafe(36)
    private_key, public_key = generate_keypair()
    values = {
        "DOMAIN": domain,
        "LOG_LEVEL": "info",
        "HUB_REPLICAS": "2",
        "CONTROL_PLANE_VERSION": "local",
        "POSTGRES_PASSWORD": postgres_password,
        "DATABASE_URL": (
            "postgresql+asyncpg://control_plane:"
            f"{postgres_password}@postgres:5432/control_plane"
        ),
        "ADMIN_TOKEN": "m42_owner_" + secrets.token_urlsafe(36),
        "AGENT_BOOTSTRAP_TOKEN": "m42_agent_" + secrets.token_urlsafe(36),
        "REMOTE_COMMAND_TWO_PERSON_APPROVAL": "true",
        "EMERGENCY_CONSOLE_ENABLED": "false",
        "EMERGENCY_TOTP_SECRET": "",
        "ED25519_PUBLIC_KEY": public_key,
        "LICENSE_SIGNING_PRIVATE_KEY": private_key,
        # Billing remains inert until an operator replaces these values.
        "STRIPE_SECRET_KEY": "not_configured",
        "STRIPE_WEBHOOK_SECRET": "not_configured",
        "STRIPE_PRODUCT_PLANS_JSON": "{}",
        "BILLING_EMAIL_ENABLED": "false",
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        "# Generated by scripts/bootstrap_cloud.py. Keep this file private.\n"
        "# Stripe billing is disabled until its three not_configured values are replaced.\n"
        + "\n".join(f"{key}={value}" for key, value in values.items())
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    os.chmod(temporary, 0o600)
    os.replace(temporary, path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--domain", required=True, help="Public dashboard hostname")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    write_config(args.output.resolve(), domain=args.domain, force=args.force)
    print(f"Created {args.output.resolve()}")
    print("Keep this file private; it contains database, owner, agent, and signing secrets.")
    print("Stripe billing is disabled until its placeholder values are replaced.")


if __name__ == "__main__":
    main()
