#!/usr/bin/env python3
"""Create a secure local configuration for the self-hosted quickstart."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import secrets


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "deploy" / "self-host.env"
PUBLIC_LICENSE_KEY = "31iGBIN15cAlkXmYXYLwZTXJYR9Yngjzf187Bf+s+xA="


def write_config(path: Path, *, force: bool) -> None:
    if path.exists() and not force:
        raise SystemExit(f"Refusing to overwrite {path}. Use --force to replace it.")

    values = {
        "ADMIN_TOKEN": "m42_owner_" + secrets.token_urlsafe(32),
        "AGENT_BOOTSTRAP_TOKEN": "m42_agent_" + secrets.token_urlsafe(32),
        "BIND_ADDRESS": "127.0.0.1",
        "HUB_PORT": "8080",
        "DASHBOARD_PORT": "3000",
        "CORS_ORIGINS": "http://localhost:3000",
        "ED25519_PUBLIC_KEY": PUBLIC_LICENSE_KEY,
        "LOG_LEVEL": "info",
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        "# Generated by scripts/bootstrap_self_host.py. Keep this file private.\n"
        + "\n".join(f"{key}={value}" for key, value in values.items())
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    os.chmod(temporary, 0o600)
    os.replace(temporary, path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    output = args.output.resolve()
    write_config(output, force=args.force)
    print(f"Created {output}")
    print("Keep this file private; it contains the owner and agent credentials.")
    print("Next: docker compose --env-file deploy/self-host.env "
          "-f deploy/docker-compose.hub.yml up -d --build")


if __name__ == "__main__":
    main()
